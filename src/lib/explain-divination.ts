/* --------------------------------- 查询辅助 -------------------------------- */

/**
 * 在字典中查找术语解释。支持常见后缀容错：
 * 「休门」可查「休」，「天蓬星」可查「天蓬」，反之亦然。
 */
export function explainOf(dict: ExplainDict, key: string | undefined | null): string | undefined {
  if (!key) return undefined;
  const k = key.trim();
  if (!k) return undefined;
  if (dict[k]) return dict[k];
  // 尝试去/加常见后缀
  const bare = k.replace(/(门|星|神|将|卦)$/, "");
  if (dict[bare]) return dict[bare];
  for (const suffix of ["门", "星", "神", "将"]) {
    if (dict[k + suffix]) return dict[k + suffix];
  }
  return undefined;
}
