/**
 * 从指定字典取白话解释；key 不在字典中时返回 undefined。
 * 支持「天乙贵人（年柱）」之类带括注的 key，自动截掉括号再查。
 */
export function explainOf(dict: Record<string, string>, key: string): string | undefined {
  if (!key) return undefined;
  const cleaned = key.trim();
  if (dict[cleaned]) return dict[cleaned];
  // 去掉尾部的括注/修饰再试一次
  const stripped = cleaned.replace(/[（(].*$/, "").trim();
  if (stripped && dict[stripped]) return dict[stripped];
  // 字典 key 是术语子串的情况（如神煞「红鸾星动」命中「红鸾」）
  for (const k of Object.keys(dict)) {
    if (k.length >= 2 && cleaned.includes(k)) return dict[k];
  }
  return undefined;
}

/** 在全部内置字典中查找术语解释 */
export function explainTerm(term: string): string | undefined {
  for (const dict of ALL_DICTS) {
    const hit = explainOf(dict, term);
    if (hit) return hit;
  }
  return undefined;
}
