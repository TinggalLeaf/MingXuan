function buildSticks(): LingqianStick[] {
  const sticks: LingqianStick[] = [];
  for (let i = 0; i < 92; i++) {
    const p = POEM_BANK[i % POEM_BANK.length];
    sticks.push({
      no: i + 1,
      level: p.level,
      palace: PALACES[i % 12] + (Math.floor(i / 12) + 1) + "宫",
      verse: p.verse,
      summary: p.summary,
      body: p.body,
    });
  }
  return sticks;
}

export const LINGQIAN_STICKS: ReadonlyArray<LingqianStick> = buildSticks();

/** 抽签：均匀随机取一支。 */
export function drawLingqianStick(rng: () => number = Math.random): LingqianStick {
  const idx = Math.floor(rng() * LINGQIAN_STICKS.length);
  return LINGQIAN_STICKS[Math.max(0, Math.min(LINGQIAN_STICKS.length - 1, idx))];
}
